    @Override
    public void visit(Ast.Stmt.Ldc s) {
        // double类型需要使用ldc2_w指令
        if (s.i instanceof java.lang.Double) {
            // 添加d后缀明确指定double类型
            this.iwriteln("ldc2_w " + s.i + "d");
        } else {
            this.iwriteln("ldc " + s.i);
        }
    }

    @Override
    public void visit(Ast.Stmt.Printf obj) {
        if( obj.exprType.getKind() == TypeKind.INT){
            this.iwriteln("getstatic java/lang/System/out Ljava/io/PrintStream;");
            this.iwriteln("swap");
            this.iwriteln("invokevirtual java/io/PrintStream/print(I)V");
        }
        else if( obj.exprType.getKind() == TypeKind.FLOAT){
            this.iwriteln("getstatic java/lang/System/out Ljava/io/PrintStream;");
            this.iwriteln("swap");
            this.iwriteln("invokevirtual java/io/PrintStream/print(F)V");
        }
        else if( obj.exprType.getKind() == TypeKind.DOUBLE){
            this.iwriteln("getstatic java/lang/System/out Ljava/io/PrintStream;");
            this.iwriteln("dup_x2");
            this.iwriteln("pop");
            this.iwriteln("invokevirtual java/io/PrintStream/print(D)V");
        }
        else if( obj.exprType.getKind() == TypeKind.STRING){
            this.iwriteln("getstatic java/lang/System/out Ljava/io/PrintStream;");
            this.iwriteln("swap");
            this.iwriteln("invokevirtual java/io/PrintStream/print(Ljava/lang/String;)V");
        }
    }

