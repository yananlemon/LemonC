package site.ilemon.codegen;

import site.ilemon.ast.Ast;
import site.ilemon.visitor.ISemanticVisitor;

import java.io.BufferedWriter;
import java.io.File;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.OutputStreamWriter;
import java.util.HashMap;
import java.util.Map;

/**
 * x86-64 汇编代码生成器（Windows NASM 格式）
 * 
 * 生成 Windows x64 汇编代码，使用 Microsoft x64 调用约定
 */
public class X86_64Generator implements ISemanticVisitor {
    
    private StringBuilder dataSection = new StringBuilder();
    private StringBuilder textSection = new StringBuilder();
    private int labelCounter = 0;
    private int stringCounter = 0;
    private int stackOffset = 0;
    private Map<String, Integer> varOffsets = new HashMap<>();
    private String currentMethod = "";
    
    private BufferedWriter writer;
    private File outputFile;
    
    public X86_64Generator() {
        this(new File("output.asm"));
    }
    
    public X86_64Generator(File outputFile) {
        this.outputFile = outputFile;
    }
    
    private void emit(String format, Object... args) {
        textSection.append(String.format(format, args)).append("\n");
    }
    
    private void emitData(String format, Object... args) {
        dataSection.append(String.format(format, args)).append("\n");
    }
    
    private String newLabel() {
        return ".L" + (labelCounter++);
    }
    
    private String addString(String str) {
        String label = "str" + (stringCounter++);
        // 处理转义字符
        str = str.replace("\\n", "\", 10, \"");
        emitData("    %s db \"%s\", 0", label, str);
        return label;
    }
    
    // ========== Program & Class ==========
    
    @Override
    public void visit(Ast.Program.T programSingle) {
        Ast.Program.ProgramSingle prog = (Ast.Program.ProgramSingle) programSingle;
        this.visit(prog.getMainClass());
    }
    
    @Override
    public void visit(Ast.MainClass.T obj) {
        Ast.MainClass.MainClassSingle mainClass = (Ast.MainClass.MainClassSingle) obj;
        
        try {
            writer = new BufferedWriter(new OutputStreamWriter(
                new FileOutputStream(outputFile), "UTF-8"));
            
            // 写入文件头
            writer.write("; Generated by LemonC Native Compiler\n");
            writer.write("; Target: Windows x64 (NASM)\n\n");
            
            // 数据段
            writer.write("section .data\n");
            
            // 遍历所有方法，收集字符串
            for (Ast.Method.T method : mainClass.getMethods()) {
                this.visit(method);
            }
            
            // 写入数据段
            writer.write(dataSection.toString());
            writer.write("\n");
            
            // 代码段
            writer.write("section .text\n");
            writer.write("    global main\n");
            writer.write("    extern printf\n");
            writer.write("    extern ExitProcess\n\n");
            
            // 写入代码段
            writer.write(textSection.toString());
            
            writer.close();
            
        } catch (IOException e) {
            throw new RuntimeException("Failed to write assembly file: " + e.getMessage());
        }
    }
    
    // ========== Method ==========
    
    // Dispatcher method for Method.T interface
    public void visit(Ast.Method.T method) {
        if (method instanceof Ast.Method.MethodSingle) {
            visit((Ast.Method.MethodSingle) method);
        }
    }
    
    @Override
    public void visit(Ast.Method.MethodSingle obj) {
        currentMethod = obj.getId();
        varOffsets.clear();
        stackOffset = 0;
        
        if (obj.getId().equals("main")) {
            emit("main:");
            emit("    push rbp");
            emit("    mov rbp, rsp");
            emit("    sub rsp, 128        ; 预留栈空间");
            emit("");
            
            // 生成方法体
            for (Ast.Stmt.T stmt : obj.getStms()) {
                this.visit(stmt);
            }
            
            // 退出程序
            emit("");
            emit("    ; 退出程序");
            emit("    xor rcx, rcx        ; exit code 0");
            emit("    call ExitProcess");
        }
    }
    
    // ========== Statements ==========
    
    @Override
    public void visit(Ast.Stmt.T obj) {
        if (obj != null) {
            obj.accept(this);
        }
    }
    
    @Override
    public void visit(Ast.Stmt.Assign obj) {
        emit("    ; %s = ...", obj.getId().getId());
        
        // 分配栈空间（如果是新变量）
        String varName = obj.getId().getId();
        if (!varOffsets.containsKey(varName)) {
            stackOffset += 8;
            varOffsets.put(varName, stackOffset);
        }
        
        // 计算表达式，结果在 rax
        this.visit(obj.getExpr());
        
        // 存储到栈
        int offset = varOffsets.get(varName);
        emit("    mov [rbp - %d], rax", offset);
        emit("");
    }
    
    @Override
    public void visit(Ast.Stmt.Printf obj) {
        emit("    ; printf(\"%s\", ...)", obj.getFormat());
        
        // 添加格式字符串到数据段
        String formatLabel = addString(obj.getFormat());
        
        // Windows x64 调用约定：rcx, rdx, r8, r9
        // 需要为前4个参数预留 shadow space (32字节)
        
        if (obj.getExprs() == null || obj.getExprs().isEmpty()) {
            // 只有格式字符串
            emit("    lea rcx, [%s]", formatLabel);
            emit("    sub rsp, 32         ; shadow space");
            emit("    call printf");
            emit("    add rsp, 32");
        } else {
            // 有参数
            // 先计算所有参数并压栈
            for (int i = obj.getExprs().size() - 1; i >= 0; i--) {
                this.visit(obj.getExprs().get(i));
                emit("    push rax");
            }
            
            // 加载参数到寄存器
            emit("    lea rcx, [%s]", formatLabel);
            String[] regs = {"rdx", "r8", "r9"};
            for (int i = 0; i < Math.min(obj.getExprs().size(), 3); i++) {
                emit("    pop %s", regs[i]);
            }
            
            // 调用 printf
            emit("    sub rsp, 32         ; shadow space");
            emit("    call printf");
            emit("    add rsp, 32");
        }
        emit("");
    }
    
    @Override
    public void visit(Ast.Stmt.Block obj) {
        for (Ast.Stmt.T stmt : obj.getStmts()) {
            this.visit(stmt);
        }
    }
    
    @Override
    public void visit(Ast.Stmt.If obj) {
        String elseLabel = newLabel();
        String endLabel = newLabel();
        
        emit("    ; if statement");
        this.visit(obj.getCondition());
        emit("    cmp rax, 0");
        emit("    je %s", elseLabel);
        
        this.visit(obj.getThenStmt());
        emit("    jmp %s", endLabel);
        
        emit("%s:", elseLabel);
        if (obj.getElseStmt() != null) {
            this.visit(obj.getElseStmt());
        }
        
        emit("%s:", endLabel);
        emit("");
    }
    
    @Override
    public void visit(Ast.Stmt.While obj) {
        String startLabel = newLabel();
        String endLabel = newLabel();
        
        emit("    ; while loop");
        emit("%s:", startLabel);
        
        this.visit(obj.getCondition());
        emit("    cmp rax, 0");
        emit("    je %s", endLabel);
        
        this.visit(obj.getBody());
        emit("    jmp %s", startLabel);
        
        emit("%s:", endLabel);
        emit("");
    }
    
    // ========== Expressions ==========
    
    @Override
    public void visit(Ast.Expr.T obj) {
        if (obj != null) {
            obj.accept(this);
        }
    }
    
    @Override
    public void visit(Ast.Expr.Number obj) {
        if (obj.getType() instanceof Ast.Type.Int) {
            emit("    mov rax, %s", obj.getValue());
        }
    }
    
    @Override
    public void visit(Ast.Expr.Id obj) {
        int offset = varOffsets.get(obj.getId());
        emit("    mov rax, [rbp - %d]", offset);
    }
    
    @Override
    public void visit(Ast.Expr.Add obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    add rax, rbx");
    }
    
    @Override
    public void visit(Ast.Expr.Sub obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    sub rax, rbx");
    }
    
    @Override
    public void visit(Ast.Expr.Mul obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    imul rax, rbx");
    }
    
    @Override
    public void visit(Ast.Expr.Div obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    xor rdx, rdx");
        emit("    idiv rbx");
    }
    
    @Override
    public void visit(Ast.Expr.GT obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    cmp rax, rbx");
        emit("    setg al");
        emit("    movzx rax, al");
    }
    
    @Override
    public void visit(Ast.Expr.LT obj) {
        this.visit(obj.getLeft());
        emit("    push rax");
        this.visit(obj.getRight());
        emit("    mov rbx, rax");
        emit("    pop rax");
        emit("    cmp rax, rbx");
        emit("    setl al");
        emit("    movzx rax, al");
    }
    
    // ========== 未实现的方法（占位） ==========
    
    @Override public void visit(Ast.Type.T obj) {}
    @Override public void visit(Ast.Type.Bool obj) {}
    @Override public void visit(Ast.Type.Float obj) {}
    @Override public void visit(Ast.Type.Double obj) {}
    @Override public void visit(Ast.Type.Str obj) {}
    @Override public void visit(Ast.Type obj) {}
    @Override public void visit(Ast.Type.Void obj) {}
    @Override public void visit(Ast.Type.Int obj) {}
    @Override public void visit(Ast.Declare.T obj) {}
    @Override public void visit(Ast.Expr obj) {}
    @Override public void visit(Ast.Expr.And obj) {}
    @Override public void visit(Ast.Expr.Call obj) {}
    @Override public void visit(Ast.Expr.LTE obj) {}
    @Override public void visit(Ast.Expr.GTE obj) {}
    @Override public void visit(Ast.Expr.EQ obj) {}
    @Override public void visit(Ast.Expr.NEQ obj) {}
    @Override public void visit(Ast.Expr.Or obj) {}
    @Override public void visit(Ast.Expr.True obj) {}
    @Override public void visit(Ast.Expr.False obj) {}
    @Override public void visit(Ast.Expr.Not obj) {}
    @Override public void visit(Ast.Expr.Str obj) {}
    @Override public void visit(Ast.Stmt.PrintLine obj) {}
    @Override public void visit(Ast.Stmt.Return obj) {}
    @Override public void visit(Ast.Stmt.Break obj) {}
    @Override public void visit(Ast.Stmt.Continue obj) {}
    @Override public void visit(Ast.Stmt.Call obj) {}
    @Override public void visit(Ast.Type.IntArray obj) {}
    @Override public void visit(Ast.Type.FloatArray obj) {}
    @Override public void visit(Ast.Type.DoubleArray obj) {}
    @Override public void visit(Ast.Type.BoolArray obj) {}
    @Override public void visit(Ast.Expr.ArrayAccess obj) {}
    @Override public void visit(Ast.Expr.ArrayLength obj) {}
    @Override public void visit(Ast.Stmt.ArrayAssign obj) {}
    
    public File getOutputFile() {
        return outputFile;
    }
}
